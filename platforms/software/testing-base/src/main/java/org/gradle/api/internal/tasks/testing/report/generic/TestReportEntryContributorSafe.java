package org.gradle.api.internal.tasks.testing.report.generic;

import org.gradle.api.tasks.testing.TestReportEntryContent;
import org.gradle.api.tasks.testing.TestReportEntryContributor;
import org.gradle.api.tasks.testing.TestReportEntryContext;
import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;

/**
 * Wraps a {@link TestReportEntryContributor}, so that all calls into it describe which contributor failed when they
 * throw.
 *
 * <p>
 * This intentionally doesn't implement {@link TestReportEntryContributor}, so it can't be confused with an unwrapped
 * contributor.
 * </p>
 */
@NullMarked
public final class TestReportEntryContributorSafe {
    private final TestReportEntryContributor delegate;

    public TestReportEntryContributorSafe(TestReportEntryContributor delegate) {
        this.delegate = delegate;
    }

    public String getContributorClassName() {
        return delegate.getClass().getName();
    }

    public String getEntryName() {
        try {
            return delegate.getEntryName();
        } catch (Exception e) {
            throw new GenericHtmlReportGenerationException(
                "Could not get the entry name of test report entry contributor " + getContributorClassName() + ".",
                e
            );
        }
    }

    /**
     * Returns the content of the entry, or {@code null} if the entry should not be shown.
     */
    @Nullable
    public HtmlContent contentFor(TestReportEntryContext context) {
        TestReportEntryContent content;
        try {
            content = delegate.contentFor(context);
        } catch (Exception e) {
            throw renderFailure(e);
        }
        // We still have to handle a potential null return
        //noinspection ConstantValue
        if (content == null) {
            throw new IllegalStateException(
                String.format("Test report entry contributor %s returned null content for '%s', use TestReportEntryContent.empty() instead.", getContributorClassName(), getEntryName())
            );
        }
        // We map to HtmlContent here, in the future if we add some kind of "safe DSL" it would also be mapped to
        // HtmlContent here, to prevent changes in the implementation of report generation.
        // Essentially, this is the boundary at which we validate and trust the content, and anything that calls HtmlContent
        // trusts the HTML generated by it.
        if (content instanceof EmptyTestReportEntryContent) {
            return null;
        }
        if (content instanceof HtmlTestReportEntryContent) {
            return new HtmlContent((HtmlTestReportEntryContent) content);
        }
        throw new IllegalStateException("Unsupported test report entry content type: " + content.getClass().getName());
    }

    private GenericHtmlReportGenerationException renderFailure(Exception cause) {
        return new GenericHtmlReportGenerationException(
            String.format("Could not render custom test report entry '%s' with %s.", getEntryName(), getContributorClassName()),
            cause
        );
    }

    /**
     * HTML content of an entry, with additional failure information if writing the HTML fails.
     */
    public final class HtmlContent {
        private final HtmlTestReportEntryContent content;

        private HtmlContent(HtmlTestReportEntryContent content) {
            this.content = content;
        }

        public void writeHtml(Appendable htmlOut) {
            try {
                // Purposefully nested, we want to catch the exception on close.
                try (ContainmentCheckingAppendable checkedOut = new ContainmentCheckingAppendable(htmlOut)) {
                    content.getWriter().writeHtml(checkedOut);
                }
            } catch (Exception e) {
                throw renderFailure(e);
            }
        }
    }
}
